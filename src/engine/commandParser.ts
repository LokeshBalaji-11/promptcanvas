import { MoodboardProject } from '../types';
import { generateMoodboard } from './moodboardGenerator';

export function parseAiCommand(currentBoard: MoodboardProject, rawCommand: string): { updatedBoard: MoodboardProject; explanation: string; generatedCode: string } {
  const cmd = rawCommand.toLowerCase().trim();
  let updatedBoard = JSON.parse(JSON.stringify(currentBoard)) as MoodboardProject;
  let explanation = `Executed command: "${rawCommand}"`;

  // 1. Color changes (e.g. "change primary color to #ff2a5f" or "make it neon cyan")
  const hexMatch = cmd.match(/#([0-9a-f]{3,6})/i);
  if (cmd.includes('color') || hexMatch) {
    let newHex = hexMatch ? `#${hexMatch[1]}` : '#CCFF00';
    if (cmd.includes('cyan')) newHex = '#00F0FF';
    else if (cmd.includes('rose') || cmd.includes('pink') || cmd.includes('red')) newHex = '#FF2A5F';
    else if (cmd.includes('volt') || cmd.includes('lime') || cmd.includes('green')) newHex = '#CCFF00';
    else if (cmd.includes('orange')) newHex = '#F97316';
    else if (cmd.includes('purple') || cmd.includes('indigo')) newHex = '#8B5CF6';

    updatedBoard.accentColor = newHex;
    if (updatedBoard.palette[2]) {
      updatedBoard.palette[2].hex = newHex;
      updatedBoard.palette[2].name = 'AI Custom Accent';
    }
    explanation = `Updated primary accent color to ${newHex}.`;
  } 
  // 2. Light / Dark mode switch
  else if (cmd.includes('light mode') || cmd.includes('light theme')) {
    updatedBoard.palette[0].hex = '#f8fafc';
    updatedBoard.palette[1].hex = '#ffffff';
    explanation = `Switched canvas base to light mode.`;
  }
  else if (cmd.includes('dark mode') || cmd.includes('dark theme')) {
    updatedBoard.palette[0].hex = '#060608';
    updatedBoard.palette[1].hex = '#0a0b10';
    explanation = `Switched canvas base to dark mode.`;
  }
  // 3. Typography changes
  else if (cmd.includes('serif') || cmd.includes('editorial font')) {
    updatedBoard.fonts.display = 'Playfair Display';
    explanation = `Switched display typography to Playfair Display serif.`;
  }
  else if (cmd.includes('grotesk') || cmd.includes('sans')) {
    updatedBoard.fonts.display = 'Space Grotesk';
    explanation = `Switched display typography to Space Grotesk.`;
  }
  // 4. Create brand new board
  else if (cmd.includes('create') || cmd.includes('new board') || cmd.includes('generate')) {
    const promptText = rawCommand.replace(/create|new|board|for/gi, '').trim() || 'Futuristic AI neural interface';
    updatedBoard = generateMoodboard(promptText, 'Cinematic');
    explanation = `Generated new board for: "${promptText}".`;
  }
  // 5. Hero title change
  else if (cmd.includes('title') || cmd.includes('hero')) {
    const titleText = rawCommand.replace(/change hero title to|title to|hero to/gi, '').trim();
    if (titleText && updatedBoard.cards[0]) {
      updatedBoard.cards[0].title = titleText;
      explanation = `Updated primary storyboard card title to "${titleText}".`;
    }
  }
  else {
    // Fallback: treat as prompt generation
    updatedBoard = generateMoodboard(rawCommand, 'Cinematic');
    explanation = `Synthesized new aesthetic system for "${rawCommand}".`;
  }

  updatedBoard.updatedAt = Date.now();

  const generatedCode = `<!-- Generated by PromptCanvas AI Engine -->
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>${updatedBoard.title}</title>
  <link href="${updatedBoard.fonts.googleFontsUrl}" rel="stylesheet">
  <style>
    :root {
      --bg: ${updatedBoard.palette[0].hex};
      --surface: ${updatedBoard.palette[1].hex};
      --primary: ${updatedBoard.accentColor};
      --text: #f8fafc;
    }
    body { background: var(--bg); color: var(--text); font-family: '${updatedBoard.fonts.body}', sans-serif; margin: 0; padding: 60px; }
    h1 { font-family: '${updatedBoard.fonts.display}', sans-serif; color: var(--primary); font-size: 3rem; margin-bottom: 20px; }
    .card { background: var(--surface); border: 1px solid rgba(255,255,255,0.1); border-radius: 20px; padding: 30px; margin-top: 20px; }
    .btn { background: var(--primary); color: #000; padding: 12px 24px; border-radius: 12px; font-weight: bold; border: none; cursor: pointer; }
  </style>
</head>
<body>
  <h1>${updatedBoard.title}</h1>
  <p>${updatedBoard.prompt}</p>
  <div class="card">
    <h3>Live Preview Component</h3>
    <p>Lighting: ${updatedBoard.lighting}</p>
    <button class="btn">Explore System</button>
  </div>
</body>
</html>`;

  return { updatedBoard, explanation, generatedCode };
}
